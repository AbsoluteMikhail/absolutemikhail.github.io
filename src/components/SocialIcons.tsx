import React, { forwardRef } from 'react';

// 1. Расширяем стандартные пропсы SVG. Теперь иконка принимает onClick, style, id и т.д.
export interface IconProps extends React.SVGProps<SVGSVGElement> {
    size?: number | string;
}

const getIconClassName = (className?: string) =>
    ["icon-svg", className].filter(Boolean).join(" ");

// 2. Оборачиваем в forwardRef для прокидывания ссылок на DOM-узел
export const BaseIcon = forwardRef<SVGSVGElement, IconProps>(({
                                                                  size = '1em', // 3. 1em - суперсила. Иконка автоматически будет размером с текущий текст
                                                                  className,
                                                                  viewBox = "0 0 24 24",
                                                                  children,
                                                                  ...rest // 4. Собираем все остальные пропсы
                                                              }, ref) => {
    return (
        <svg
            ref={ref}
            width={size}
            height={size}
            viewBox={viewBox}
            fill="currentColor"
            className={getIconClassName(className)}
            // Базовые атрибуты для доступности (чтобы скринридеры не читали мусор)
            aria-hidden="true"
            focusable="false"
            xmlns="http://www.w3.org/2000/svg"
            {...rest} // Прокидываем всё остальное в DOM
        >
            {children}
        </svg>
    );
});

// React DevTools будет нормально показывать имя компонента
BaseIcon.displayName = 'BaseIcon';

